/// Langues faites dans le code : (index dans `CATALOG`, colonne du dictionnaire ; 0 = français).
pub const DONE: [(usize, usize); 3] = [(0, 0), (1, 1), (5, 2)];
/// Colonne des packs téléchargés.
const PACK_COL: usize = 3;

static LANG: AtomicUsize = AtomicUsize::new(0);
/// Pack actif : (index dans `CATALOG`, phrases).
static PACK: RwLock<Option<(usize, &'static HashMap<&'static str, &'static str>)>> = RwLock::new(None);

/// Langue choisie (index dans `CATALOG`) : faite dans le code, ou le pack déjà chargé ; sinon le français.
pub fn set_lang(k: usize) {
    let col = match DONE.iter().find(|(l, _)| *l == k) {
        Some((_, c)) => *c,
        None if PACK.read().ok().and_then(|p| p.map(|(i, _)| i)) == Some(k) => PACK_COL,
        None => 0,
    };
    if LANG.swap(col, Ordering::Relaxed) != col {
        VERSION.fetch_add(1, Ordering::Relaxed);
    }
}

/// Changes of language or pack so far: an image kept from before a change is drawn again.
static VERSION: AtomicUsize = AtomicUsize::new(0);

/// How many times the language (or its pack) was set: an image kept with another number is out of date.
pub fn version() -> usize {
    VERSION.load(Ordering::Relaxed)
}

/// Active le pack de la langue `k` (phrase française → traduction) ; le pack est gardé tant qu'Argos tourne.
pub fn set_pack(k: usize, phrases: HashMap<String, String>) {
    let map: HashMap<&'static str, &'static str> = phrases
        .into_iter()
        .filter(|(_, v)| !v.is_empty())
        .map(|(f, t)| (&*Box::leak(f.into_boxed_str()), &*Box::leak(t.into_boxed_str())))
        .collect();
    if let Ok(mut p) = PACK.write() {
        *p = Some((k, Box::leak(Box::new(map))));
    }
    VERSION.fetch_add(1, Ordering::Relaxed);
    set_lang(k);
}

/// Langue du catalogue pour ce qu'on tape (nom, code ou mot comme « allemand », sans tenir compte des accents).
pub fn find(query: &str) -> Option<usize> {
    let q = plain(query.trim());
    if q.is_empty() {
        return None;
    }
    let words = |k: usize| format!("{} {} {}", plain(CATALOG[k].1), plain(CATALOG[k].0), CATALOG[k].2);
    (0..CATALOG.len())
        .find(|&k| plain(CATALOG[k].1) == q || plain(CATALOG[k].0) == q)
        .or_else(|| (0..CATALOG.len()).find(|&k| words(k).split(' ').any(|w| w.starts_with(&q)) || words(k).contains(&q)))
}

/// Minuscules sans accents (pour la recherche).
pub fn plain(s: &str) -> String {
    s.to_lowercase()
        .chars()
        .map(|c| match c {
            'à' | 'á' | 'â' | 'ä' | 'ã' | 'ă' => 'a',
            'é' | 'è' | 'ê' | 'ë' | 'ə' | 'ệ' => 'e',
            'í' | 'ì' | 'î' | 'ï' => 'i',
            'ó' | 'ò' | 'ô' | 'ö' | 'õ' | 'ʻ' => 'o',
            'ú' | 'ù' | 'û' | 'ü' | 'ữ' => 'u',
            'ç' | 'č' => 'c',
            'š' => 's',
            'ž' => 'z',
            other => other,
        })
        .collect()
}

/// Cette langue de la liste est-elle faite ?
pub fn done(k: usize) -> bool {
    DONE.iter().any(|(l, _)| *l == k)
}

fn dict() -> &'static HashMap<&'static str, (&'static str, &'static str)> {
    static D: OnceLock<HashMap<&'static str, (&'static str, &'static str)>> = OnceLock::new();
    D.get_or_init(|| DICT.iter().map(|(fr, en, es)| (*fr, (*en, *es))).collect())
}

fn word(fr: &str, col: usize) -> Option<&'static str> {
    if col == PACK_COL {
        return PACK.read().ok().and_then(|p| p.and_then(|(_, m)| m.get(fr).copied()));
    }
    dict().get(fr).map(|(en, es)| if col == 1 { *en } else { *es })
}

/// `s` dans la langue choisie.
pub fn tr(s: &str) -> Cow<'_, str> {
    match LANG.load(Ordering::Relaxed) {
        0 => Cow::Borrowed(s),
        col => tr_in(s, col),
    }
}

fn tr_in(s: &str, col: usize) -> Cow<'_, str> {
    if let Some(t) = word(s, col) {
        return Cow::Borrowed(t);
    }
    let soon = match col {
        1 => "soon",
        2 => "pronto",
        _ => word("bientôt", col).unwrap_or("soon"),
    };
    for suffix in ["  (bientôt)", " (bientôt)"] {
        if let Some(base) = s.strip_suffix(suffix) {
            return Cow::Owned(format!("{} ({soon})", tr_in(base, col)));
        }
    }
    for sep in [" : ", " · ", " — "] {
        if s.contains(sep) {
            let parts: Vec<Cow<str>> = s.split(sep).map(|p| tr_in(p, col)).collect();
            if parts.iter().any(|p| matches!(p, Cow::Owned(_)) || word(p, col).is_none()) {
                let joined = parts.join(sep);
                if joined != s {
                    return Cow::Owned(joined);
                }
            }
        }
    }
    Cow::Borrowed(s)
}

