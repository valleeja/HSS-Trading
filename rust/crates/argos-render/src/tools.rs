#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn catalogue_complet_comme_v1() {
        assert_eq!(TOOLS.len(), 109, "93 de v1 + les 16 outils de LuxAlgo");
        // chaque outil de la barre existe dans la table, et a son icône
        for item in RAIL {
            let ids: Vec<&str> = match item {
                RailItem::Tool(id) => vec![*id],
                RailItem::Group(g) => g.sections.iter().flat_map(|(_, l)| l.iter().copied()).collect(),
            };
            for id in ids {
                assert!(def(id).is_some(), "outil inconnu : {id}");
                assert!(crate::icons::has(id), "icône manquante : {id}");
            }
        }
        let mut seen = std::collections::HashSet::new();
        assert!(TOOLS.iter().all(|t| seen.insert(t.id)), "un id par outil");
        assert_eq!(def("trend").map(|t| (t.points, t.key)), Some((2, "T")));
    }
}
